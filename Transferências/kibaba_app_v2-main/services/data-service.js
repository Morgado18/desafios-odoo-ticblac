// Service functions
let likedPostsState = []
let likedCommentsState = []

export const toggleLikePost = (postId) => {
  if (likedPostsState.includes(postId)) {
    likedPostsState = likedPostsState.filter((id) => id !== postId)
    return false
  } else {
    likedPostsState.push(postId)
    return true
  }
}

export const toggleLikeComment = (commentId) => {
  if (likedCommentsState.includes(commentId)) {
    likedCommentsState = likedCommentsState.filter((id) => id !== commentId)
    return false
  } else {
    likedCommentsState.push(commentId)
    return true
  }
}

export const getLikedPosts = () => {
  return likedPostsState
}

export const getLikedComments = () => {
  return likedCommentsState
}

export const addComment = (postId, comment) => {
  const story = stories.find((s) => s.id === postId)
  if (story) {
    const newComment = {
      id: Date.now(),
      author: currentUser.name,
      avatar: currentUser.avatar,
      content: comment,
      date: "Agora mesmo",
      likes: 0,
    }
    story.comments.push(newComment)
    story.comments = [...story.comments]
    return newComment
  }
  return null
}

export const addDiscussionReply = (discussionId, reply) => {
  const discussion = discussions.find((d) => d.id === discussionId)
  if (discussion) {
    const newReply = {
      id: Date.now(),
      author: currentUser.name,
      avatar: currentUser.avatar,
      content: reply,
      date: "Agora mesmo",
      likes: 0,
    }
    discussion.replies.push(newReply)
    return newReply
  }
  return null
}

